/// One generated sequence and its per-position target class.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct QuinticItem {
    /// Input symbols, one of [`TURN_A`] / [`TURN_B`] / [`RESET`].
    pub symbols: Vec<usize>,
    /// Per-position target class, in `0..group.num_classes()`.
    pub targets: Vec<i64>,
}

/// An in-memory dataset of generated [`QuinticItem`]s.
pub struct QuinticDataset {
    dataset: InMemDataset<QuinticItem>,
}

impl QuinticDataset {
    /// Generate `num_sequences` sequences of one family, seeded deterministically.
    pub fn new(
        group: Group,
        num_sequences: usize,
        seq_length: usize,
        family: Family,
        seed: u64,
    ) -> Self {
        let mut state = seed;
        let items = (0..num_sequences)
            .map(|_| {
                let symbols = generate(family, &mut state, seq_length);
                let targets = labels(group, &symbols);
                QuinticItem { symbols, targets }
            })
            .collect();
        Self {
            dataset: InMemDataset::new(items),
        }
    }
}

impl Dataset<QuinticItem> for QuinticDataset {
    fn get(&self, index: usize) -> Result<QuinticItem, DatasetError> {
        self.dataset.get(index)
    }
    fn len(&self) -> usize {
        self.dataset.len()
    }
}

/// Collates [`QuinticItem`]s into a [`QuinticBatch`], one-hotting the symbols.
#[derive(Clone, Debug, Default)]
pub struct QuinticBatcher {}

/// A batch of one-hot symbol sequences and their per-position target classes.
#[derive(Clone, Debug)]
pub struct QuinticBatch {
    /// One-hot input symbol at each position, `[batch, seq, NUM_SYMBOLS]`.
    pub inputs: Tensor<3>,
    /// Per-position target class, `[batch, seq]`.
    pub targets: Tensor<2, Int>,
}

impl QuinticBatch {
    /// The batch, built by a dataloader worker on the host, moved to `device`
    /// by the thread that steps the model (see `device::loader_device`).
    pub fn to_device(self, device: &Device) -> Self {
        use crate::common::device::{batch_float, batch_int};
        Self {
            inputs: batch_float(self.inputs, device),
            targets: batch_int(self.targets, device),
        }
    }
}

/// One-hot encode a symbol sequence into `[seq, NUM_SYMBOLS]`.
pub fn one_hot(symbols: &[usize], device: &Device) -> Tensor<2> {
    let mut buf = vec![0.0f32; symbols.len() * NUM_SYMBOLS];
    for (t, &s) in symbols.iter().enumerate() {
        buf[t * NUM_SYMBOLS + s] = 1.0;
    }
    Tensor::<1>::from_floats(buf.as_slice(), device).reshape([symbols.len(), NUM_SYMBOLS])
}

impl Batcher<QuinticItem, QuinticBatch> for QuinticBatcher {
    fn batch(&self, items: Vec<QuinticItem>, device: &Device) -> QuinticBatch {
        let inputs: Vec<Tensor<2>> = items
            .iter()
            .map(|item| one_hot(&item.symbols, device))
            .collect();
        let targets: Vec<Tensor<1, Int>> = items
            .iter()
            .map(|item| Tensor::<1, Int>::from_ints(item.targets.as_slice(), device))
            .collect();
        QuinticBatch {
            inputs: Tensor::stack(inputs, 0),
            targets: Tensor::stack(targets, 0),
        }
    }
}
